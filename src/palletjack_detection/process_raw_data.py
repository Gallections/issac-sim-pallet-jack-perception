"""Copy selected raw RGB/KITTI files and convert copied labels for training."""

from __future__ import annotations

import argparse
import csv
import shutil
from dataclasses import dataclass
from pathlib import Path

from palletjack_detection.kitti_to_yolo import convert_kitti_annotation_file_to_yolo
from palletjack_detection.validate_dataset import KittiExportValidationError, validate_kitti_object_detection_export

SPLIT_NAMES = ("train", "validation", "test")
EXPECTED_MANIFEST_FIELDS = {
    "split",
    "scenario",
    "frame_id",
    "source_image_path",
    "kitti_annotation_path",
    "processed_image_path",
    "processed_kitti_annotation_path",
    "yolo_annotation_path",
}
PROCESSED_MARKER = ".generated_by_process_raw_data"
PROCESSED_MARKER_CONTENT = "Generated by scripts/process_raw_data.py. Safe to replace through that command.\n"
GENERATED_PATH_NAMES = ("images", "kitti_labels", "labels", "dataset.yaml")


@dataclass
class ProcessedRawDataResult:
    source_root: Path
    manifest_dir: Path
    output_root: Path
    copied_image_count: int
    copied_kitti_annotation_count: int
    converted_yolo_annotation_count: int
    dataset_yaml: Path


@dataclass(frozen=True)
class RawFrameProcessPlan:
    image_source: Path
    kitti_annotation_source: Path
    processed_image: Path
    processed_kitti_annotation: Path
    yolo_annotation: Path


def _resolve_manifest_path(root: Path, relative_path: str, field_name: str) -> Path:
    relative = Path(relative_path)
    if relative.is_absolute():
        raise ValueError(f"{field_name} must be a relative path: {relative_path}")
    resolved = (root / relative).resolve()
    if not resolved.is_relative_to(root.resolve()):
        raise ValueError(f"{field_name} escapes its root: {relative_path}")
    return resolved


def _build_raw_frame_processing_plans(
    source_root: Path,
    output_root: Path,
    manifest_rows: list[dict[str, str]],
) -> list[RawFrameProcessPlan]:
    plans: list[RawFrameProcessPlan] = []
    output_paths: set[Path] = set()
    for row in manifest_rows:
        image_source = _resolve_manifest_path(source_root, row["source_image_path"], "source_image_path")
        kitti_source = _resolve_manifest_path(source_root, row["kitti_annotation_path"], "kitti_annotation_path")
        processed_image = _resolve_manifest_path(output_root, row["processed_image_path"], "processed_image_path")
        processed_kitti = _resolve_manifest_path(
            output_root, row["processed_kitti_annotation_path"], "processed_kitti_annotation_path"
        )
        yolo_annotation = _resolve_manifest_path(output_root, row["yolo_annotation_path"], "yolo_annotation_path")
        for source_path in (image_source, kitti_source):
            if not source_path.is_file():
                raise FileNotFoundError(f"manifest source file does not exist: {source_path}")
        for output_path in (processed_image, processed_kitti, yolo_annotation):
            if output_path in output_paths:
                raise ValueError(f"multiple manifest rows target the same processed file: {output_path}")
            output_paths.add(output_path)
        plans.append(
            RawFrameProcessPlan(
                image_source=image_source,
                kitti_annotation_source=kitti_source,
                processed_image=processed_image,
                processed_kitti_annotation=processed_kitti,
                yolo_annotation=yolo_annotation,
            )
        )
    return plans


def _read_split_manifest_rows(manifest_dir: Path) -> list[dict[str, str]]:
    all_rows: list[dict[str, str]] = []
    frame_keys: set[tuple[str, str]] = set()
    for split_name in SPLIT_NAMES:
        manifest_path = manifest_dir / f"{split_name}.csv"
        with manifest_path.open(newline="", encoding="utf-8") as manifest_file:
            reader = csv.DictReader(manifest_file)
            if reader.fieldnames is None or not EXPECTED_MANIFEST_FIELDS.issubset(reader.fieldnames):
                raise ValueError(f"{manifest_path} is missing required split-manifest columns")
            for row in reader:
                if row["split"] != split_name:
                    raise ValueError(f"{manifest_path} contains a row assigned to {row['split']!r}")
                frame_key = (row["scenario"], row["frame_id"])
                if frame_key in frame_keys:
                    raise ValueError(f"frame appears more than once in split manifests: {frame_key}")
                frame_keys.add(frame_key)
                all_rows.append(row)
    if not all_rows:
        raise ValueError(f"split manifests contain no frame rows: {manifest_dir}")
    return all_rows


def _remove_prior_processed_outputs(output_root: Path) -> None:
    marker = output_root / PROCESSED_MARKER
    if not marker.is_file() or marker.read_text(encoding="utf-8") != PROCESSED_MARKER_CONTENT:
        raise FileExistsError(f"refusing to replace unrecognized processed-data outputs under {output_root}")
    for relative_name in GENERATED_PATH_NAMES:
        target = output_root / relative_name
        if target.is_symlink():
            raise FileExistsError(f"refusing to remove generated-output symlink: {target}")
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()


def process_raw_export_from_manifests(
    source_root: str | Path,
    manifest_dir: str | Path,
    output_root: str | Path,
    *,
    inclusive_max_coordinates: bool = True,
    overwrite: bool = False,
) -> ProcessedRawDataResult:
    """Copy split RGB/KITTI inputs and convert their copied annotations to YOLO."""
    source = Path(source_root).expanduser().resolve()
    manifests = Path(manifest_dir).expanduser().resolve()
    destination = Path(output_root).expanduser().resolve()
    rows = _read_split_manifest_rows(manifests)
    manifest_scenarios = tuple(sorted({row["scenario"] for row in rows}))
    validation_report = validate_kitti_object_detection_export(source, scenario_names=manifest_scenarios)
    if not validation_report.ok:
        raise KittiExportValidationError(validation_report)
    expected_frame_count = sum(scenario.image_count for scenario in validation_report.scenarios)
    if len(rows) != expected_frame_count:
        raise ValueError(
            f"split manifests include {len(rows)} frames but the validated source contains {expected_frame_count}"
        )
    processing_plans = _build_raw_frame_processing_plans(source, destination, rows)

    destination.mkdir(parents=True, exist_ok=True)
    existing_outputs = [destination / name for name in (*GENERATED_PATH_NAMES, PROCESSED_MARKER)]
    if any(path.exists() for path in existing_outputs):
        if not overwrite:
            raise FileExistsError(f"processed-data outputs already exist under {destination} (pass overwrite=True)")
        _remove_prior_processed_outputs(destination)
    (destination / PROCESSED_MARKER).write_text(PROCESSED_MARKER_CONTENT, encoding="utf-8")

    copied_images = 0
    copied_kitti_annotations = 0
    converted_yolo_annotations = 0
    for plan in processing_plans:
        plan.processed_image.parent.mkdir(parents=True, exist_ok=True)
        plan.processed_kitti_annotation.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(plan.image_source, plan.processed_image)
        shutil.copy2(plan.kitti_annotation_source, plan.processed_kitti_annotation)
        copied_images += 1
        copied_kitti_annotations += 1
        convert_kitti_annotation_file_to_yolo(
            plan.processed_kitti_annotation,
            plan.processed_image,
            plan.yolo_annotation,
            inclusive_max_coordinates=inclusive_max_coordinates,
        )
        converted_yolo_annotations += 1

    (destination / "dataset.yaml").write_text(
        "path: .\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n\n"
        "names:\n"
        "  0: palletjack\n",
        encoding="utf-8",
        newline="\n",
    )
    return ProcessedRawDataResult(
        source_root=source,
        manifest_dir=manifests,
        output_root=destination,
        copied_image_count=copied_images,
        copied_kitti_annotation_count=copied_kitti_annotations,
        converted_yolo_annotation_count=converted_yolo_annotations,
        dataset_yaml=destination / "dataset.yaml",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Copy split RGB/KITTI data into processed and convert labels to YOLO.")
    parser.add_argument("--root", type=Path, default=Path("data/raw"), help="raw source-data root")
    parser.add_argument("--manifest-dir", type=Path, default=Path("data/processed/splits"), help="split CSV directory")
    parser.add_argument("--output-dir", type=Path, default=Path("data/processed"), help="processed-data root")
    parser.add_argument(
        "--exclusive-max-coordinates",
        action="store_true",
        help="treat KITTI x_max/y_max as exclusive edges; default treats them as inclusive pixels",
    )
    parser.add_argument("--overwrite", action="store_true", help="replace outputs previously generated by this script")
    args = parser.parse_args(argv)
    try:
        result = process_raw_export_from_manifests(
            args.root,
            args.manifest_dir,
            args.output_dir,
            inclusive_max_coordinates=not args.exclusive_max_coordinates,
            overwrite=args.overwrite,
        )
    except KittiExportValidationError as exc:
        print(f"Dataset validation failed: {exc}")
        for issue in exc.report.issues[:50]:
            location = f"{issue.scenario}/{issue.path}" if issue.scenario else issue.path
            print(f"  {location}: {issue.message}")
        if len(exc.report.issues) > 50:
            print(f"  ... {len(exc.report.issues) - 50} additional issue(s) not shown")
        return 1
    except (FileExistsError, FileNotFoundError, OSError, ValueError) as exc:
        print(f"Could not process raw dataset: {exc}")
        return 1
    print(
        f"Copied {result.copied_image_count} RGB images and "
        f"{result.copied_kitti_annotation_count} KITTI labels; converted "
        f"{result.converted_yolo_annotation_count} labels to YOLO under {result.output_root}"
    )
    print(f"YOLO dataset config: {result.dataset_yaml}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
