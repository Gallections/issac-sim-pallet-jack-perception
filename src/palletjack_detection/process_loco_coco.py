"""Prepare the public LOCO COCO annotations as a one-class pallet-jack dataset."""

from __future__ import annotations

import argparse
import copy
import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RAW_ROOT = PROJECT_ROOT / "data" / "raw" / "real-pallet-jack-data"
DEFAULT_OUTPUT_ROOT = PROJECT_ROOT / "data" / "processed" / "real-pallet-jack-data"
SOURCE_CATEGORY_NAME = "pallet_truck"
TARGET_CATEGORY_ID = 1
TARGET_CATEGORY_NAME = "pallet-jack"
IMAGE_SUFFIXES = {".bmp", ".jpeg", ".jpg", ".png", ".tif", ".tiff", ".webp"}
GENERATED_MARKER = ".generated_by_process_loco_coco"
GENERATED_MARKER_CONTENT = "Generated by scripts/process_loco_coco.py. Safe to replace through that command.\n"
GENERATED_OUTPUTS = ("images", "annotations.json", "processing_report.json")


@dataclass(frozen=True)
class ProcessLocoCocoResult:
    """Counts and paths produced while preparing one-class COCO data."""

    output_root: Path
    annotation_path: Path
    report_path: Path
    source_image_record_count: int
    raw_image_file_count: int
    copied_image_count: int
    target_annotation_count: int
    target_image_count: int
    negative_image_count: int
    removed_annotation_count: int
    unmatched_image_files: tuple[str, ...]


def filter_coco_to_pallet_jack(coco_data: dict[str, Any]) -> dict[str, Any]:
    """Return a copy of COCO data containing only remapped pallet-truck boxes.

    All COCO image records are retained, including images that have no
    pallet-truck annotations. Annotation IDs, image IDs, segmentation data,
    and dataset metadata are preserved.
    """
    if not isinstance(coco_data, dict):
        raise ValueError("COCO data must be a JSON object")
    for key in ("images", "annotations", "categories"):
        if not isinstance(coco_data.get(key), list):
            raise ValueError(f"COCO data must contain a {key!r} list")

    source_categories = [
        category for category in coco_data["categories"]
        if category.get("name") == SOURCE_CATEGORY_NAME
    ]
    if len(source_categories) != 1:
        raise ValueError(
            f"expected exactly one {SOURCE_CATEGORY_NAME!r} category, found {len(source_categories)}"
        )
    source_category_id = source_categories[0].get("id")

    image_ids = [image.get("id") for image in coco_data["images"]]
    if None in image_ids or len(set(image_ids)) != len(image_ids):
        raise ValueError("COCO image records must have unique, non-missing IDs")
    category_ids = [category.get("id") for category in coco_data["categories"]]
    if None in category_ids or len(set(category_ids)) != len(category_ids):
        raise ValueError("COCO categories must have unique, non-missing IDs")

    image_id_set = set(image_ids)
    category_id_set = set(category_ids)
    retained_annotations: list[dict[str, Any]] = []
    for annotation in coco_data["annotations"]:
        image_id = annotation.get("image_id")
        category_id = annotation.get("category_id")
        if image_id not in image_id_set:
            raise ValueError(f"annotation {annotation.get('id')!r} references unknown image_id {image_id!r}")
        if category_id not in category_id_set:
            raise ValueError(
                f"annotation {annotation.get('id')!r} references unknown category_id {category_id!r}"
            )
        if category_id == source_category_id:
            remapped = copy.deepcopy(annotation)
            remapped["category_id"] = TARGET_CATEGORY_ID
            retained_annotations.append(remapped)

    filtered = copy.deepcopy(coco_data)
    target_category = copy.deepcopy(source_categories[0])
    target_category["id"] = TARGET_CATEGORY_ID
    target_category["name"] = TARGET_CATEGORY_NAME
    filtered["categories"] = [target_category]
    filtered["annotations"] = retained_annotations
    return filtered


def _resolve_source_image(image_root: Path, image_record: dict[str, Any]) -> Path:
    """Resolve the dataset-relative source path without allowing root escape."""
    relative_value = image_record.get("path") or image_record.get("file_name")
    if not isinstance(relative_value, str) or not relative_value:
        raise ValueError(f"COCO image {image_record.get('id')!r} has no usable path or file_name")
    relative_path = Path(relative_value)
    if relative_path.is_absolute():
        raise ValueError(f"COCO image path must be relative: {relative_value}")
    resolved = (image_root / relative_path).resolve()
    if not resolved.is_relative_to(image_root.resolve()):
        raise ValueError(f"COCO image path escapes the raw image root: {relative_value}")
    return resolved


def _remove_previous_outputs(output_root: Path) -> None:
    marker = output_root / GENERATED_MARKER
    if not marker.is_file() or marker.read_text(encoding="utf-8") != GENERATED_MARKER_CONTENT:
        raise FileExistsError(f"refusing to replace unrecognized processed data under {output_root}")
    for relative_name in (*GENERATED_OUTPUTS, GENERATED_MARKER):
        target = output_root / relative_name
        if target.is_symlink():
            raise FileExistsError(f"refusing to replace generated-output symlink: {target}")
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()


def prepare_loco_pallet_jack_dataset(
    annotation_path: str | Path,
    image_root: str | Path,
    output_dir: str | Path,
    *,
    overwrite: bool = False,
) -> ProcessLocoCocoResult:
    """Copy COCO-listed images and write a one-class pallet-jack COCO file.

    Image files present in ``image_root`` but absent from the COCO ``images``
    array are reported and left in the raw directory; they are not represented
    as negative examples in the processed COCO file.
    """
    source_annotations = Path(annotation_path).expanduser().resolve()
    source_image_root = Path(image_root).expanduser().resolve()
    destination = Path(output_dir).expanduser().resolve()
    if not source_annotations.is_file():
        raise FileNotFoundError(f"COCO annotation file does not exist: {source_annotations}")
    if not source_image_root.is_dir():
        raise FileNotFoundError(f"raw image root does not exist: {source_image_root}")
    if destination == source_image_root or destination.is_relative_to(source_image_root):
        raise ValueError("processed output must not be inside the raw image root")
    if source_image_root.is_relative_to(destination) or source_annotations.is_relative_to(destination):
        raise ValueError("processed output must not contain source images or annotations")

    with source_annotations.open(encoding="utf-8") as annotation_file:
        source_data = json.load(annotation_file)
    filtered_data = filter_coco_to_pallet_jack(source_data)

    copy_plan: list[tuple[Path, Path, dict[str, Any]]] = []
    resolved_source_paths: set[Path] = set()
    destination_relative_paths: set[Path] = set()
    for image_record in filtered_data["images"]:
        source_path = _resolve_source_image(source_image_root, image_record)
        if not source_path.is_file():
            raise FileNotFoundError(f"COCO-listed image does not exist: {source_path}")
        if source_path in resolved_source_paths:
            raise ValueError(f"multiple COCO image records resolve to the same file: {source_path}")
        resolved_source_paths.add(source_path)
        relative_path = source_path.relative_to(source_image_root)
        if relative_path in destination_relative_paths:
            raise ValueError(f"multiple COCO records target the same processed image: {relative_path}")
        destination_relative_paths.add(relative_path)
        image_record["file_name"] = relative_path.as_posix()
        if "path" in image_record:
            image_record["path"] = relative_path.as_posix()
        copy_plan.append((source_path, relative_path, image_record))

    all_source_images = sorted(
        path for path in source_image_root.rglob("*")
        if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
    )
    unmatched_images = tuple(
        path.relative_to(source_image_root).as_posix()
        for path in all_source_images
        if path not in resolved_source_paths
    )

    destination.mkdir(parents=True, exist_ok=True)
    if any(destination.iterdir()):
        if not overwrite:
            raise FileExistsError(
                f"processed-data outputs already exist under {destination} (pass --overwrite to replace generated outputs)"
            )
        _remove_previous_outputs(destination)
    (destination / GENERATED_MARKER).write_text(GENERATED_MARKER_CONTENT, encoding="utf-8")

    image_output_root = destination / "images"
    for source_path, relative_path, _ in copy_plan:
        target_path = image_output_root / relative_path
        target_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_path, target_path)

    processed_annotation_path = destination / "annotations.json"
    processed_annotation_path.write_text(
        json.dumps(filtered_data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    target_image_ids = {annotation["image_id"] for annotation in filtered_data["annotations"]}
    summary = {
        "source_annotations": str(source_annotations),
        "source_image_root": str(source_image_root),
        "source_image_record_count": len(source_data["images"]),
        "raw_image_file_count": len(all_source_images),
        "copied_image_count": len(copy_plan),
        "target_category": TARGET_CATEGORY_NAME,
        "target_annotation_count": len(filtered_data["annotations"]),
        "target_image_count": len(target_image_ids),
        "negative_image_count": len(filtered_data["images"]) - len(target_image_ids),
        "removed_annotation_count": len(source_data["annotations"]) - len(filtered_data["annotations"]),
        "unmatched_image_count": len(unmatched_images),
        "unmatched_image_files": list(unmatched_images),
    }
    report_path = destination / "processing_report.json"
    report_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")

    return ProcessLocoCocoResult(
        output_root=destination,
        annotation_path=processed_annotation_path,
        report_path=report_path,
        source_image_record_count=len(source_data["images"]),
        raw_image_file_count=len(all_source_images),
        copied_image_count=len(copy_plan),
        target_annotation_count=len(filtered_data["annotations"]),
        target_image_count=len(target_image_ids),
        negative_image_count=len(filtered_data["images"]) - len(target_image_ids),
        removed_annotation_count=len(source_data["annotations"]) - len(filtered_data["annotations"]),
        unmatched_image_files=unmatched_images,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Prepare one-class pallet-jack COCO data from the staged LOCO subset."
    )
    parser.add_argument("--root", type=Path, default=DEFAULT_RAW_ROOT, help="raw LOCO dataset directory")
    parser.add_argument(
        "--annotations",
        type=Path,
        default=None,
        help="source COCO JSON (default: <root>/loco-all-v1.json)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_ROOT,
        help="processed output directory",
    )
    parser.add_argument("--overwrite", action="store_true", help="replace outputs previously generated by this script")
    args = parser.parse_args(argv)
    annotation_path = args.annotations or args.root / "loco-all-v1.json"
    try:
        result = prepare_loco_pallet_jack_dataset(
            annotation_path,
            args.root,
            args.output_dir,
            overwrite=args.overwrite,
        )
    except (FileExistsError, FileNotFoundError, OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"Could not prepare LOCO COCO data: {exc}")
        return 1

    print(
        f"Prepared {result.copied_image_count} COCO-listed images: "
        f"{result.target_image_count} with pallet-jack boxes and {result.negative_image_count} without."
    )
    print(
        f"Kept {result.target_annotation_count} pallet-jack boxes; "
        f"removed {result.removed_annotation_count} annotations for other classes."
    )
    print(
        f"Found {len(result.unmatched_image_files)} raw image files without COCO image records; "
        "they remain in raw data and are not treated as negatives."
    )
    print(f"Filtered annotations: {result.annotation_path}")
    print(f"Processing report: {result.report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
