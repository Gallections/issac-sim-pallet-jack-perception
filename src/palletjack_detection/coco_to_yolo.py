"""Convert COCO detection boxes to Ultralytics YOLO label files."""

from __future__ import annotations

import argparse
import json
import math
import shutil
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from PIL import Image

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATASET_ROOT = PROJECT_ROOT / "data" / "processed" / "real-pallet-jack-data"
GENERATED_MARKER = ".generated_by_convert_coco_to_yolo"
GENERATED_MARKER_CONTENT = "Generated by scripts/convert_coco_to_yolo.py. Safe to replace through that command.\n"
GENERATED_OUTPUTS = ("labels", "dataset.yaml", "conversion_report.json")


@dataclass(frozen=True)
class CocoToYoloResult:
    """Summary of converted labels and dataset configuration."""

    dataset_root: Path
    dataset_yaml: Path
    report_path: Path
    image_count: int
    positive_image_count: int
    negative_image_count: int
    annotation_count: int
    class_names: tuple[str, ...]


def _validate_coco(coco_data: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[Any, int], tuple[str, ...]]:
    if not isinstance(coco_data, dict):
        raise ValueError("COCO data must be a JSON object")
    for key in ("images", "annotations", "categories"):
        if not isinstance(coco_data.get(key), list):
            raise ValueError(f"COCO data must contain a {key!r} list")

    categories = coco_data["categories"]
    category_ids = [category.get("id") for category in categories]
    if not categories or any(category_id is None for category_id in category_ids):
        raise ValueError("COCO categories must have non-missing IDs")
    if len(set(category_ids)) != len(category_ids):
        raise ValueError("COCO categories must have unique IDs")
    if any(not isinstance(category.get("name"), str) or not category["name"] for category in categories):
        raise ValueError("COCO categories must have non-empty names")
    ordered_categories = sorted(categories, key=lambda category: category["id"])
    class_id_by_category_id = {
        category["id"]: class_index for class_index, category in enumerate(ordered_categories)
    }
    class_names = tuple(category["name"] for category in ordered_categories)

    image_ids = [image.get("id") for image in coco_data["images"]]
    if any(image_id is None for image_id in image_ids) or len(set(image_ids)) != len(image_ids):
        raise ValueError("COCO image records must have unique, non-missing IDs")
    image_id_set = set(image_ids)
    category_id_set = set(category_ids)
    annotations_by_image: dict[Any, list[dict[str, Any]]] = defaultdict(list)
    for annotation in coco_data["annotations"]:
        image_id = annotation.get("image_id")
        category_id = annotation.get("category_id")
        if image_id not in image_id_set:
            raise ValueError(f"annotation {annotation.get('id')!r} references unknown image_id {image_id!r}")
        if category_id not in category_id_set:
            raise ValueError(f"annotation {annotation.get('id')!r} references unknown category_id {category_id!r}")
        annotations_by_image[image_id].append(annotation)
    return annotations_by_image, class_id_by_category_id, class_names


def _resolve_image_path(image_root: Path, image_record: dict[str, Any]) -> tuple[Path, Path]:
    relative_value = image_record.get("path") or image_record.get("file_name")
    if not isinstance(relative_value, str) or not relative_value:
        raise ValueError(f"COCO image {image_record.get('id')!r} has no usable path or file_name")
    relative_path = Path(relative_value)
    if relative_path.is_absolute():
        raise ValueError(f"COCO image path must be relative: {relative_value}")
    resolved_path = (image_root / relative_path).resolve()
    if not resolved_path.is_relative_to(image_root.resolve()):
        raise ValueError(f"COCO image path escapes the image root: {relative_value}")
    if not resolved_path.is_file():
        raise FileNotFoundError(f"COCO-listed image does not exist: {resolved_path}")
    return resolved_path, relative_path


def _format_yolo_bbox(annotation: dict[str, Any], image_width: int, image_height: int) -> tuple[float, float, float, float]:
    bbox = annotation.get("bbox")
    if not isinstance(bbox, list) or len(bbox) != 4:
        raise ValueError(f"annotation {annotation.get('id')!r} must have a four-value COCO bbox")
    try:
        x_min, y_min, box_width, box_height = (float(value) for value in bbox)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"annotation {annotation.get('id')!r} has a non-numeric COCO bbox") from exc
    if not all(math.isfinite(value) for value in (x_min, y_min, box_width, box_height)):
        raise ValueError(f"annotation {annotation.get('id')!r} has non-finite COCO bbox values")
    if x_min < 0 or y_min < 0 or box_width <= 0 or box_height <= 0:
        raise ValueError(f"annotation {annotation.get('id')!r} has an invalid COCO bbox extent")
    if x_min + box_width > image_width or y_min + box_height > image_height:
        raise ValueError(
            f"annotation {annotation.get('id')!r} COCO bbox is outside image bounds {image_width}x{image_height}"
        )
    center_x = (x_min + box_width / 2) / image_width
    center_y = (y_min + box_height / 2) / image_height
    return center_x, center_y, box_width / image_width, box_height / image_height


def convert_coco_to_yolo_labels(
    coco_data: dict[str, Any],
    image_root: str | Path,
    label_root: str | Path,
) -> CocoToYoloResult:
    """Write one normalized YOLO label file per COCO image, including negatives."""
    images_root = Path(image_root).expanduser().resolve()
    labels_root = Path(label_root).expanduser().resolve()
    if not images_root.is_dir():
        raise FileNotFoundError(f"image root does not exist: {images_root}")
    if labels_root == images_root or labels_root.is_relative_to(images_root):
        raise ValueError("YOLO labels must be stored outside the image directory")

    annotations_by_image, class_id_by_category_id, class_names = _validate_coco(coco_data)
    plan: list[tuple[Path, list[str]]] = []
    seen_image_paths: set[Path] = set()
    seen_label_paths: set[Path] = set()
    positive_image_ids: set[Any] = set()
    annotation_count = 0

    for image_record in coco_data["images"]:
        image_path, relative_image_path = _resolve_image_path(images_root, image_record)
        label_path = relative_image_path.with_suffix(".txt")
        if image_path in seen_image_paths or label_path in seen_label_paths:
            raise ValueError(f"multiple COCO image records resolve to the same image or label path: {relative_image_path}")
        seen_image_paths.add(image_path)
        seen_label_paths.add(label_path)
        with Image.open(image_path) as image:
            image_width, image_height = image.size
        if image_width <= 0 or image_height <= 0:
            raise ValueError(f"image has invalid dimensions: {image_path}")

        lines: list[str] = []
        for annotation in annotations_by_image.get(image_record["id"], []):
            class_id = class_id_by_category_id[annotation["category_id"]]
            box_values = _format_yolo_bbox(annotation, image_width, image_height)
            lines.append(f"{class_id} " + " ".join(f"{value:.8g}" for value in box_values))
        if lines:
            positive_image_ids.add(image_record["id"])
        annotation_count += len(lines)
        plan.append((label_path, lines))

    labels_root.mkdir(parents=True, exist_ok=True)
    for relative_label_path, lines in plan:
        output_path = labels_root / relative_label_path
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8", newline="\n")

    return CocoToYoloResult(
        dataset_root=labels_root.parent,
        dataset_yaml=labels_root.parent / "dataset.yaml",
        report_path=labels_root.parent / "conversion_report.json",
        image_count=len(coco_data["images"]),
        positive_image_count=len(positive_image_ids),
        negative_image_count=len(coco_data["images"]) - len(positive_image_ids),
        annotation_count=annotation_count,
        class_names=class_names,
    )


def _remove_previous_conversion(dataset_root: Path) -> None:
    marker = dataset_root / GENERATED_MARKER
    if not marker.is_file() or marker.read_text(encoding="utf-8") != GENERATED_MARKER_CONTENT:
        raise FileExistsError(f"refusing to replace unrecognized COCO-to-YOLO outputs under {dataset_root}")
    for relative_name in (*GENERATED_OUTPUTS, GENERATED_MARKER):
        target = dataset_root / relative_name
        if target.is_symlink():
            raise FileExistsError(f"refusing to replace generated-output symlink: {target}")
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()


def convert_coco_dataset_to_yolo(
    annotation_path: str | Path,
    dataset_root: str | Path,
    *,
    overwrite: bool = False,
) -> CocoToYoloResult:
    """Convert a COCO JSON beside its images and write an Ultralytics test YAML."""
    annotations_path = Path(annotation_path).expanduser().resolve()
    root = Path(dataset_root).expanduser().resolve()
    image_root = root / "images"
    if not annotations_path.is_file():
        raise FileNotFoundError(f"COCO annotation file does not exist: {annotations_path}")
    if not root.is_dir():
        raise FileNotFoundError(f"dataset root does not exist: {root}")
    if root == image_root or annotations_path.is_relative_to(root / "labels"):
        raise ValueError("COCO annotations and images must remain outside the generated labels directory")
    try:
        coco_data = json.loads(annotations_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"COCO annotation file is not valid JSON: {annotations_path}: {exc}") from exc

    existing_outputs = [root / name for name in GENERATED_OUTPUTS]
    if any(path.exists() for path in existing_outputs):
        if not overwrite:
            raise FileExistsError(f"COCO-to-YOLO outputs already exist under {root} (pass --overwrite to replace generated outputs)")
        _remove_previous_conversion(root)

    result = convert_coco_to_yolo_labels(coco_data, image_root, root / "labels")
    yaml_values = {
        "path": str(root),
        "train": None,
        "val": None,
        "test": "images",
        "names": {index: name for index, name in enumerate(result.class_names)},
    }
    (root / "dataset.yaml").write_text(yaml.safe_dump(yaml_values, sort_keys=False), encoding="utf-8", newline="\n")
    report = {
        "source_annotations": str(annotations_path),
        "image_root": str(image_root),
        "dataset_yaml": str(root / "dataset.yaml"),
        "image_count": result.image_count,
        "positive_image_count": result.positive_image_count,
        "negative_image_count": result.negative_image_count,
        "annotation_count": result.annotation_count,
        "class_names": list(result.class_names),
    }
    (root / "conversion_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (root / GENERATED_MARKER).write_text(GENERATED_MARKER_CONTENT, encoding="utf-8", newline="\n")
    return CocoToYoloResult(
        dataset_root=root,
        dataset_yaml=root / "dataset.yaml",
        report_path=root / "conversion_report.json",
        image_count=result.image_count,
        positive_image_count=result.positive_image_count,
        negative_image_count=result.negative_image_count,
        annotation_count=result.annotation_count,
        class_names=result.class_names,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Convert COCO detection annotations to YOLO labels for evaluation.")
    parser.add_argument("--dataset-root", type=Path, default=DEFAULT_DATASET_ROOT, help="processed dataset root containing images/")
    parser.add_argument("--annotations", type=Path, default=None, help="COCO JSON (default: <dataset-root>/annotations.json)")
    parser.add_argument("--overwrite", action="store_true", help="replace outputs previously generated by this converter")
    args = parser.parse_args(argv)
    annotation_path = args.annotations or args.dataset_root / "annotations.json"
    try:
        result = convert_coco_dataset_to_yolo(annotation_path, args.dataset_root, overwrite=args.overwrite)
    except (FileExistsError, FileNotFoundError, OSError, ValueError) as exc:
        print(f"Could not convert COCO annotations to YOLO: {exc}")
        return 1

    print(f"Converted {result.annotation_count} boxes for {result.image_count} images")
    print(f"Positive images: {result.positive_image_count}; negative images: {result.negative_image_count}")
    print(f"Dataset YAML: {result.dataset_yaml}")
    print(f"Conversion report: {result.report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
